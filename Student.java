//contains student info
public class Student{
    String rollNumber;
    String name;
    String department;
    String branch;
    int section;
    String email;
    String phoneNumber;
    Student(String rollNumber,String name,String department,String branch,int section,String email,String phoneNumber){
        this.rollNumber=rollNumber;
        this.name=name;
        this.department=department;
        this.branch=branch;
        this.section=section;
        this.email=email;
        this.phoneNumber=phoneNumber;

    }
}
